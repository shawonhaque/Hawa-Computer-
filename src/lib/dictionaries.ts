const dictionaries = { bn, en };
export type Dict = typeof bn;

export function getDict(locale: Locale): Dict {
  return dictionaries[locale] ?? bn;
}

/** Pick the localised field from a bilingual record, e.g. pick(service, "name", locale). */
export function pick<T = string>(record: Record<string, unknown>, base: string, locale: Locale): T {
  return record[`${base}${locale === "bn" ? "Bn" : "En"}`] as T;
}

export function statusLabel(locale: Locale, status: string): string {
  const dict = getDict(locale);
  return (dict.status as Record<string, string>)[status] ?? status;
}
